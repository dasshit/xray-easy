export XRAY_EASY_BACKEND_IP="${XRAY_EASY_RUNTIME_BACKEND_IP:-172.31.244.3}"

exec docker compose \
  --project-directory "$repo_root" \
  -f "$repo_root/compose.yaml" \
  -f "$repo_root/compose.xray-runtime.yaml" \
  "$@"
