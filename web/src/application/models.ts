import type { ClientProtocol, XrayLogLevel } from '../domain/models'

/** First-run state returned by the setup endpoint. */
export type SetupStatus = {
  initialized: boolean
  /** Configured public Xray listener port, when the server includes it. */
  publicPort?: number
  /** Public IPv4 already selected during Hysteria 2 TLS setup, when present. */
  suggestedPublicHost?: string
}

/** Administrator credentials and connection settings for first-run setup. */
export type InitializeSetupCommand = {
  username: string
  password: string
  publicHost: string
  publicPort: number
  realityTarget: string
  realitySni: string
}

/** Public TLS certificate metadata returned after checking or importing a pair. */
export type HysteriaCertificateInfo = {
  subject: string
  issuer: string
  dnsNames: string[]
  ipAddresses: string[]
  notBefore: string
  notAfter: string
  fingerprint: string
}

/** Server-side Hysteria 2 inbound state; private key material is never returned. */
export type HysteriaSettings = {
  enabled: boolean
  state: string
  host: string
  udpPort: number
  tlsMode: 'custom' | 'self-signed' | 'legacy'
  tlsServerName: string
  tlsCertIp?: string
  certificateId?: string
  certificate?: HysteriaCertificateInfo
  certificateError?: string
  runtimeError?: string
  udpIdleTimeout: number
  masqueradeType: 'off' | 'string'
  masqueradeString?: string
  insecureUri: boolean
}

/** Settings submitted for review before applying a Hysteria 2 inbound change. */
export type HysteriaSettingsCommand = {
  enabled: boolean
  host: string
  tlsMode: 'custom' | 'self-signed' | 'legacy'
  tlsCertIp: string
  tlsServerName: string
  certificateId: string
  udpIdleTimeout: number
  masqueradeType: 'off' | 'string'
  masqueradeString: string
}

/** Preview of a Hysteria 2 settings change, including its no-change result. */
export type HysteriaSettingsPreview =
  | { changed: false; settings: HysteriaSettings }
  | {
      changed: true
      changeId: string
      expiresIn: number
      expectedConfirmation: string
      requiresConfirmation: boolean
      diff: Array<{ field: string; from: string; to: string }>
      consequences: string[]
      settings: HysteriaSettings
    }

/** Result returned when a certificate is staged for a later reviewed apply. */
export type HysteriaCertificateUpload = {
  certificateId: string
  certificate: HysteriaCertificateInfo
}

/** Authenticated administrator identity and optional security metadata. */
export type Admin = {
  username: string
  totpEnabled?: boolean
  /** Number of unused recovery codes, when the endpoint includes security status. */
  recoveryCodesRemaining?: number
}

/** TOTP enrollment state and the number of unused recovery codes. */
export type TOTPStatus = {
  enabled: boolean
  /** Count of one-time recovery codes that have not been used. */
  recoveryCodesRemaining: number
}

/** Temporary data needed to enroll an authenticator app. */
export type TOTPSetup = {
  setupToken: string
  /** Shared secret; disclose only during the authenticated enrollment flow. */
  secret: string
  /** The otpauth URI that can be imported into an authenticator app. */
  otpauthUri: string
  /** Base64-encoded PNG bytes for the enrollment QR code, when returned. */
  qrPng?: string
  /** One-time recovery codes shown when enrollment starts. */
  recoveryCodes: string[]
  /** Time remaining before enrollment expires, in seconds. */
  expiresIn: number
}

/** Inputs used to create a single-protocol profile; empty Hysteria auth is generated by the server. */
export type CreateClientCommand = {
  name: string
  protocol: Exclude<ClientProtocol, 'legacy_dual'>
  fingerprint?: string
  auth?: string
}

/** Authenticated VLESS delivery with a URI, QR endpoint, and client JSON configuration. */
export type VLESSProfileDelivery = {
  clientId: string
  protocol: 'vless'
  uri: string
  json: unknown
}

/** Authenticated Hysteria 2 delivery with a URI and QR endpoint. */
export type HysteriaProfileDelivery = {
  clientId: string
  protocol: 'hysteria2'
  hysteriaUri: string
}

/** Authenticated VMess delivery with a standard share link, QR endpoint, and client JSON configuration. */
export type VMessProfileDelivery = {
  clientId: string
  protocol: 'vmess'
  vmessUri: string
  json: unknown
}

/** Authenticated classic Shadowsocks delivery with a share URI and JSON profile. */
export type ShadowsocksProfileDelivery = {
  clientId: string
  protocol: 'shadowsocks'
  ssUri: string
  json: unknown
}

/** AmneziaWG profile reference; its private `.conf` stays in the AWG service. */
export type AmneziaWGProfileDelivery = {
  clientId: string
  protocol: 'amneziawg'
  name: string
}

/** Existing combined profile, retained for compatibility with migrated records. */
export type LegacyProfileDelivery = {
  clientId: string
  protocol: 'legacy_dual'
  uri?: string
  hysteriaUri?: string
  json?: unknown
}

/** Delivery payload discriminated by the protocol credentials on the profile. */
/** Authenticated Trojan delivery with a share URI and client JSON configuration. */
export type TrojanProfileDelivery = { clientId: string; protocol: 'trojan'; trojanUri: string; json: unknown }

/** Protocol-specific authenticated profile payload returned by the backend. */
export type ProfileDelivery = VLESSProfileDelivery | VMessProfileDelivery | ShadowsocksProfileDelivery | TrojanProfileDelivery | HysteriaProfileDelivery | AmneziaWGProfileDelivery | LegacyProfileDelivery

/** Proposed server settings submitted for preview before applying changes. */
export type SettingsPreviewCommand = {
  publicHost: string
  realityTarget: string
  realitySni: string
  clientFingerprint: string
  logLevel: XrayLogLevel
  /** Whether to generate a new REALITY key pair, which invalidates existing profiles. */
  rotatePrivateKey: boolean
}

/** Health and recent failure details for the embedded Xray runtime. */
export type NodeStatus = {
  /** Runtime state, including `unavailable` when status cannot be read. */
  state: string
  /** Exact Xray binary version reported by the running container. */
  xrayVersion?: string
  /** Xray version selected for the local Compose build. */
  configuredXrayVersion?: string
  /** True only when configured and running Xray both match the verified version. */
  xrayVersionVerified?: boolean
  lastError?: string
  statsLastError?: string
  xrayRuntimeError?: string
}

/** Recent diagnostic event with secrets removed by the server. */
export type DiagnosticEntry = {
  /** RFC 3339 timestamp generated by the server. */
  at: string
  /** Source component, currently `xray` or `app`. */
  component: string
  level: string
  /** Redacted diagnostic message. */
  message: string
}
